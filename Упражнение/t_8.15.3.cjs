// **Описание**: Реализуйте функцию getWeatherErrorMessage(statusCode), которая возвращает
// понятное текстовое сообщение об ошибке для CLI-приложения прогноза погоды, основываясь на числовом
// коде HTTP-ошибки, полученной при запросе к сервису погоды.
//
// **Входные данные**: statusCode (number) — числовой HTTP-код ошибки.
//
// **Выходные данные**: строка (string) — текстовое сообщение, соответствующее коду ошибки.
//
// **Ограничения**:
// - Функция должна обрабатывать следующие коды: 400, 401, 404, 500
// - Для кода 400 верните строку 'Некорректный запрос: проверьте параметры'
// - Для кода 401 верните строку 'Ошибка авторизации: проверьте API-ключ'
// - Для кода 404 верните строку 'Город не найден'
// - Для кода 500 верните строку 'Внутренняя ошибка сервера погоды'
// - Для любого другого кода (кроме указанных выше) верните строку 'Неизвестная ошибка при запросе погоды'
// - statusCode всегда является целым числом
//
// **Примеры**:
// Input: getWeatherErrorMessage(400)
// Output: 'Некорректный запрос: проверьте параметры'
//
// Input: getWeatherErrorMessage(401)
// Output: 'Ошибка авторизации: проверьте API-ключ'
//
// Input: getWeatherErrorMessage(404)
// Output: 'Город не найден'
//
// Input: getWeatherErrorMessage(500)
// Output: 'Внутренняя ошибка сервера погоды'
//
// Input: getWeatherErrorMessage(999)
// Output: 'Неизвестная ошибка при запросе погоды'

function getWeatherErrorMessage(statusCode) {
  // Ваш код здесь
  switch (statusCode) {
    case 400:
      return 'Некорректный запрос: проверьте параметры';
    case 401:
      return 'Ошибка авторизации: проверьте API-ключ';
    case 404:
      return 'Город не найден';
    case 500:
      return 'Внутренняя ошибка сервера погоды';
    default:
      return 'Неизвестная ошибка при запросе погоды';
  }
}

module.exports = { getWeatherErrorMessage };
